/**
 * One-off font fetcher: pulls the woff2 files the site actually uses from
 * Google Fonts (latin subset only) into public/fonts and writes
 * src/styles/fonts.css with local URLs. Run with `node scripts/fetch-fonts.mjs`
 * whenever the font list changes; the output is committed so builds never
 * touch the network.
 */

import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36'

// Only the weights the design system actually applies.
const FAMILIES = [
  // Body + numbers (always loaded)
  { family: 'Inter', weights: [400, 500, 600] },
  { family: 'JetBrains Mono', weights: [400, 500] },
  // Display faces — only downloaded when the visitor selects them
  { family: 'Space Grotesk', weights: [500, 600] },
  { family: 'Newsreader', weights: [400, 500] },
  { family: 'Sora', weights: [500, 600] },
  { family: 'Manrope', weights: [500, 600] },
  { family: 'Playfair Display', weights: [500, 600] },
  { family: 'Fraunces', weights: [500] },
  { family: 'Syne', weights: [600] },
  { family: 'Instrument Serif', weights: [400] },
]

const outDir = path.resolve('public/fonts')
const cssPath = path.resolve('src/styles/fonts.css')

await rm(outDir, { recursive: true, force: true })
await mkdir(outDir, { recursive: true })

const faces = []
const seen = new Set()

for (const entry of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(entry.family)}:wght@${entry.weights.join(';')}&display=swap`
  const response = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!response.ok) throw new Error(`Failed to fetch CSS for ${entry.family}: ${response.status}`)
  const css = await response.text()

  const blockPattern = /(?:\/\*\s*([a-z-]+)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g
  let match
  while ((match = blockPattern.exec(css)) !== null) {
    const subset = match[1] ?? 'unknown'
    if (subset !== 'latin') continue
    const body = match[2]

    const family = /font-family:\s*'([^']+)'/.exec(body)?.[1]
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim()
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? 'normal'
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim()
    const file = /url\((https:[^)]+\.woff2)\)/.exec(body)?.[1]
    if (!family || !weight || !file) continue

    const slug = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight.replace(/[^0-9]+/g, '-')}-latin.woff2`
    if (seen.has(slug)) continue
    seen.add(slug)

    const binary = await fetch(file, { headers: { 'User-Agent': UA } })
    if (!binary.ok) throw new Error(`Failed to fetch ${file}: ${binary.status}`)
    const buffer = Buffer.from(await binary.arrayBuffer())
    await writeFile(path.join(outDir, slug), buffer)

    faces.push({ family, weight, style, range, slug, bytes: buffer.length })
    console.log(`${slug}  ${(buffer.length / 1024).toFixed(1)} kB`)
  }
}

const header = `/* Self-hosted webfonts — generated by scripts/fetch-fonts.mjs.
   Latin subset only, display swap so text paints before the font arrives. */

`

const body = faces
  .map(
    (face) => `@font-face {
  font-family: '${face.family}';
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url('/fonts/${face.slug}') format('woff2');
${face.range ? `  unicode-range: ${face.range};\n` : ''}}`,
  )
  .join('\n\n')

await writeFile(cssPath, header + body + '\n')

const files = await readdir(outDir)
const total = faces.reduce((sum, face) => sum + face.bytes, 0)
console.log(`\n${files.length} files · ${(total / 1024).toFixed(1)} kB total → ${cssPath}`)
